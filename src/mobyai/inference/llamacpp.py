from __future__ import annotations

import os
import shutil
import stat
import subprocess
import tempfile
import urllib.request
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import TextIO

from mobyai.hardware import detect_nvidia_gpus

INSTALL_SCRIPT_URL = "https://llama.app/install.sh"
_HOME_APP = Path.home() / ".llama-app" / "llama"
_HOME_BIN = Path.home() / ".local" / "bin" / "llama"
_COMMAND_NAMES = ("llama", "llama-server")
_PREFERRED_INSTALL_DIRS = (_HOME_BIN.parent, _HOME_APP.parent)


class LlamaRuntimeError(Exception):
    """llama.cpp binary is missing or the official installer failed."""


def detect_llama_backend(path: Path) -> str:
    """Return cuda, hip, or unknown for a llama.cpp binary."""
    try:
        result = subprocess.run(
            ["ldd", str(path)],
            capture_output=True,
            text=True,
            check=False,
            timeout=5,
        )
    except (OSError, subprocess.TimeoutExpired):
        return "unknown"
    text = result.stdout.lower()
    if any(token in text for token in ("libcublas", "libggml-cuda", "libcuda.so")):
        return "cuda"
    if any(token in text for token in ("libggml-hip", "libhipblas", "libamdhip64")):
        return "hip"
    return "unknown"


def describe_llama_binary(path: Path) -> str:
    backend = detect_llama_backend(path)
    if backend == "cuda":
        return f"{path} (CUDA)"
    if backend == "hip":
        return f"{path} (ROCm/HIP — not for NVIDIA GPUs)"
    return str(path)


def llama_candidate_paths() -> list[Path]:
    seen: set[Path] = set()
    ordered: list[Path] = []
    for candidate in (_HOME_BIN, _HOME_APP):
        if candidate.is_file() and os.access(candidate, os.X_OK):
            resolved = candidate.resolve()
            if resolved not in seen:
                ordered.append(candidate)
                seen.add(resolved)
    for name in _COMMAND_NAMES:
        found = shutil.which(name)
        if not found:
            continue
        path = Path(found)
        resolved = path.resolve()
        if resolved in seen:
            continue
        ordered.append(path)
        seen.add(resolved)
    return ordered


def find_llama_binary(*, prefer_cuda: bool = True) -> Path | None:
    candidates = llama_candidate_paths()
    if not candidates:
        return None

    if prefer_cuda and detect_nvidia_gpus():
        cuda = [path for path in candidates if detect_llama_backend(path) == "cuda"]
        if cuda:
            return cuda[0]
        non_hip = [path for path in candidates if detect_llama_backend(path) != "hip"]
        if non_hip:
            return non_hip[0]
        return None
    return candidates[0]


def mobyai_env_script_path() -> Path:
    return Path.home() / "MobyAI" / "env.sh"


def render_mobyai_env(*, llama_binary: Path | None = None) -> str:
    lines = [
        "# Generated by mobyai setup. Source before running mobyai:",
        "#   source ~/MobyAI/env.sh",
        "",
    ]
    path_entries: list[str] = []
    for directory in _PREFERRED_INSTALL_DIRS:
        if directory.is_dir():
            path_entries.append(str(directory))
    if llama_binary is not None:
        bin_dir = str(llama_binary.parent)
        if bin_dir not in path_entries:
            path_entries.insert(0, bin_dir)
    if path_entries:
        joined = ":".join(path_entries)
        lines.extend(
            [
                f'export PATH="{joined}:$PATH"',
                "",
            ]
        )
    return "\n".join(lines)


def write_mobyai_env(*, llama_binary: Path | None = None, stdout: TextIO | None = None) -> Path:
    path = mobyai_env_script_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_mobyai_env(llama_binary=llama_binary), encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IXUSR)
    if stdout is not None:
        print(f"env        {path}  (source this shell snippet for PATH)", file=stdout)
    return path


def apply_mobyai_env() -> None:
    """Prepend MobyAI install dirs to the current process PATH."""
    path = mobyai_env_script_path()
    if not path.is_file():
        for directory in _PREFERRED_INSTALL_DIRS:
            if directory.is_dir():
                os.environ["PATH"] = f"{directory}:{os.environ.get('PATH', '')}"
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("export PATH="):
            value = stripped.removeprefix("export PATH=").strip().strip('"').strip("'")
            prefix = value.split(":$PATH", 1)[0]
            os.environ["PATH"] = f"{prefix}:{os.environ.get('PATH', '')}"
            return


def resolve_launch_argv(argv: Sequence[str]) -> list[str]:
    rendered = [str(part) for part in argv]
    if not rendered:
        return rendered
    first = rendered[0]
    if Path(first).expanduser().is_file() or os.sep in first or first.startswith("."):
        return rendered
    if first not in _COMMAND_NAMES:
        return rendered
    apply_mobyai_env()
    found = find_llama_binary(prefer_cuda=bool(detect_nvidia_gpus()))
    if found is not None:
        rendered[0] = str(found)
    return rendered


def ensure_llama_runtime(
    *,
    stdout: TextIO,
    skip: bool = False,
    installer: Callable[[], Path] | None = None,
    force_install: bool = False,
) -> Path:
    apply_mobyai_env()
    nvidia = bool(detect_nvidia_gpus())
    existing = find_llama_binary(prefer_cuda=nvidia)

    if existing is not None and not force_install:
        backend = detect_llama_backend(existing)
        print(f"llama.cpp  {describe_llama_binary(existing)}", file=stdout)
        if nvidia and backend == "hip":
            print(
                "WARNING  Fedora/system llama-server is ROCm-only; installing CUDA build from llama.app…",
                file=stdout,
            )
        elif nvidia and backend != "cuda":
            print(
                "WARNING  no CUDA-linked llama.cpp found; installing from llama.app…",
                file=stdout,
            )
        else:
            write_mobyai_env(llama_binary=existing, stdout=stdout)
            return existing

    if skip:
        raise LlamaRuntimeError(
            "llama.cpp is not on PATH with NVIDIA CUDA support. "
            "Install from https://llama.app or re-run setup."
        )

    if existing is None or force_install or (nvidia and detect_llama_backend(existing) != "cuda"):
        print("Installing llama.cpp CUDA build (official llama.app installer)…", file=stdout)
        install = installer or _run_official_installer
        path = install()
        apply_mobyai_env()
        found = find_llama_binary(prefer_cuda=nvidia) or path
        if found is None or not Path(found).is_file():
            raise LlamaRuntimeError("llama.cpp installer finished but no llama binary was found")
        backend = detect_llama_backend(found)
        if nvidia and backend != "cuda":
            raise LlamaRuntimeError(
                f"Installed {found} but it is not CUDA-linked ({backend}). "
                "Check https://llama.app for an NVIDIA build."
            )
        print(f"llama.cpp  {describe_llama_binary(found)}", file=stdout)
        write_mobyai_env(llama_binary=found, stdout=stdout)
        return Path(found)

    if existing is None:
        raise LlamaRuntimeError(
            "llama.cpp is not on PATH. Install from https://llama.app or re-run setup."
        )
    write_mobyai_env(llama_binary=existing, stdout=stdout)
    return existing


def _run_official_installer() -> Path:
    with tempfile.TemporaryDirectory(prefix="mobyai-llama-") as tmp:
        script = Path(tmp) / "install.sh"
        try:
            urllib.request.urlretrieve(INSTALL_SCRIPT_URL, script)
        except OSError as exc:
            raise LlamaRuntimeError(
                f"Could not download {INSTALL_SCRIPT_URL}: {exc}"
            ) from exc
        script.chmod(script.stat().st_mode | stat.S_IXUSR)
        env = os.environ.copy()
        for directory in _PREFERRED_INSTALL_DIRS:
            if directory.is_dir():
                env["PATH"] = f"{directory}:{env.get('PATH', '')}"
        try:
            subprocess.run(
                ["sh", str(script)],
                check=True,
                cwd=tmp,
                env=env,
            )
        except (OSError, subprocess.CalledProcessError) as exc:
            raise LlamaRuntimeError(f"llama.cpp installer failed: {exc}") from exc
    apply_mobyai_env()
    found = find_llama_binary(prefer_cuda=True)
    if found is None:
        raise LlamaRuntimeError("llama.cpp installer did not place a llama binary")
    return found
